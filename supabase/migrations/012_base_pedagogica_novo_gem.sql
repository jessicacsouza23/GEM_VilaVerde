-- O PWA atual usa autenticação legada por login e senha nas tabelas de
-- professoras/alunas. As políticas abaixo mantêm compatibilidade enquanto a
-- unidade ainda não usa Supabase Auth por perfil.
do $$
declare
  tabela text;
begin
  foreach tabela in array array[
    'alunas', 'professoras', 'secretarias', 'config_metodos', 'modelos_logistica',
    'calendario', 'historico_geral', 'exercicios_registro', 'folgas_professoras',
    'professoras_fixas', 'coordenacoes_professoras', 'estudo_diario',
    'licoes_feitas_alunas', 'objetivos_pedagogicos', 'avaliacoes', 'avaliacao_notas',
    'avaliacao_responsaveis', 'mensagens', 'gabaritos', 'config_visual_gem',
    'secretaria_perfil'
  ] loop
    execute format('alter table public.%I enable row level security', tabela);
    execute format('drop policy if exists "pwa acesso legado" on public.%I', tabela);
    execute format('create policy "pwa acesso legado" on public.%I for all to anon, authenticated using (true) with check (true)', tabela);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', tabela);
  end loop;
end $$;

grant usage, select on all sequences in schema public to anon, authenticated;

-- Buckets usados pelos documentos e pelos fallbacks de imagem das unidades.
insert into storage.buckets (id, name, public)
values ('gabaritos', 'gabaritos', false), ('logo_gem', 'logo_gem', false),
       ('fotos_alunas', 'fotos_alunas', false), ('fotos_professoras', 'fotos_professoras', false),
       ('fotos_secretaria_gem', 'fotos_secretaria_gem', false)
on conflict (id) do nothing;

drop policy if exists "pwa arquivos do gem" on storage.objects;
create policy "pwa arquivos do gem" on storage.objects
  for all to anon, authenticated
  using (bucket_id in ('gabaritos', 'logo_gem', 'fotos_alunas', 'fotos_professoras', 'fotos_secretaria_gem'))
  with check (bucket_id in ('gabaritos', 'logo_gem', 'fotos_alunas', 'fotos_professoras', 'fotos_secretaria_gem'));

